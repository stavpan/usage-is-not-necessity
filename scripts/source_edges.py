#!/usr/bin/env python3
"""Give the 143 fine-layer prerequisite edges a bibliographic warrant, and audit them.

`results.yml` encodes the fine layer's dependency graph as `requires: [id, ...]`
lists. Every one of the 150 rows carries `sources`, but the *edge* has nowhere to put
one: a bare list of identifiers cannot say what warrants the claim that X required Y.
That is why the transitive-reach ranking -- whose entire input is those 143 edges --
was unauditable, and it is a schema problem rather than an oversight.

This writes `data/edge-sources.yml`, one record per edge:

    - {user: newton_principia, provider: analysis_infinitesimal, sources: [boyer1991]}

The warrant is the union of the two endpoints' declared sources. That is a mechanical
derivation introducing no new judgement, and it makes every edge traceable to at least
one citable work. It is **not** verification of the dependency claim: a source that
documents the Principia does not assert that the calculus was necessary for it. The
distinction is recorded in the file's header and in the paper.

Two audits run over the same graph and can find coding errors offline:

  chronology   a prerequisite that postdates what it enables is a contradiction
  acyclicity   a cycle means an error somewhere in the loop
"""

from __future__ import annotations

import argparse
from collections import defaultdict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "data" / "results.yml"
OUT = ROOT / "data" / "edge-sources.yml"

HEADER = """# Per-edge bibliographic warrants for the fine layer's prerequisite graph.
#
# GENERATED by scripts/source_fine_edges.py -- do not hand-edit; regenerate.
#
# Why this file exists. `results.yml` encodes dependencies as `requires: [id, ...]`,
# which has no slot for a per-edge source, so the 143 edges that produce the
# transitive-reach ranking carried no citation at all and the ranking could not be
# audited. This gives each edge the union of its two endpoints' declared sources.
#
# WHAT THIS IS: traceability. Every edge now resolves to at least one citable work.
# WHAT THIS IS NOT: verification. A source documenting a result does not assert that
# its prerequisite was necessary for it. Verifying the dependency itself needs a
# dedicated citation per edge, and that remains open.
#
# `onset` is repeated from the endpoints so the chronology audit can run on this file
# alone.
"""


def load() -> list[dict]:
    return yaml.safe_load(RESULTS.read_text(encoding="utf-8"))


def edges_of(rows: list[dict]) -> list[tuple[str, str]]:
    return [(row["id"], provider) for row in rows for provider in (row.get("requires") or [])]


def audit(rows: list[dict], edges: list[tuple[str, str]]) -> dict:
    by_id = {row["id"]: row for row in rows}

    chronology = []
    for user, provider in edges:
        user_row, provider_row = by_id.get(user), by_id.get(provider)
        if not user_row or not provider_row:
            chronology.append({"user": user, "provider": provider, "issue": "unknown endpoint"})
            continue
        if provider_row["onset"] > user_row["onset"]:
            chronology.append(
                {
                    "user": user,
                    "provider": provider,
                    "user_onset": user_row["onset"],
                    "provider_onset": provider_row["onset"],
                    "gap_years": provider_row["onset"] - user_row["onset"],
                }
            )

    adjacency: dict[str, list[str]] = defaultdict(list)
    for user, provider in edges:
        adjacency[user].append(provider)
    cycles: list[list[str]] = []
    state: dict[str, int] = {}
    stack: list[str] = []

    def visit(node: str) -> None:
        state[node] = 1
        stack.append(node)
        for neighbour in adjacency.get(node, []):
            if state.get(neighbour, 0) == 1:
                cycles.append([*stack[stack.index(neighbour) :], neighbour])
            elif state.get(neighbour, 0) == 0:
                visit(neighbour)
        stack.pop()
        state[node] = 2

    for node in list(adjacency):
        if state.get(node, 0) == 0:
            visit(node)
    return {"chronology": chronology, "cycles": cycles}


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()

    rows = load()
    by_id = {row["id"]: row for row in rows}
    edges = edges_of(rows)
    print(f"fine layer: {len(rows)} rows, {len(edges)} prerequisite edges")

    records = []
    sourced = 0
    for user, provider in edges:
        union = sorted(
            set(by_id[user].get("sources") or []) | set(by_id[provider].get("sources") or [])
        )
        if union:
            sourced += 1
        records.append(
            {
                "user": user,
                "provider": provider,
                "sources": union,
                "user_onset": by_id[user]["onset"],
                "provider_onset": by_id[provider]["onset"],
            }
        )
    print(f"  edges with a non-empty warrant: {sourced} of {len(edges)}")
    print(
        "  mean sources per edge: {:.2f}   edges resting on a single source: {}".format(
            sum(len(r["sources"]) for r in records) / max(len(records), 1),
            sum(1 for r in records if len(r["sources"]) == 1),
        )
    )

    if args.write:
        # One record per line. `yaml.safe_dump` with
        # flow style wraps at an arbitrary width and produced a file that was valid
        # and unreadable; a hand-formatted line is both.
        lines = [
            "- {{user: {user}, provider: {provider}, sources: [{sources}], "
            "user_onset: {user_onset}, provider_onset: {provider_onset}}}".format(
                user=record["user"],
                provider=record["provider"],
                sources=", ".join(record["sources"]),
                user_onset=record["user_onset"],
                provider_onset=record["provider_onset"],
            )
            for record in records
        ]
        OUT.write_text(HEADER + "\n".join(lines) + "\n", encoding="utf-8")
        print(f"  wrote {OUT}")

    report = audit(rows, edges)
    print(f"\nCHRONOLOGY: {len(report['chronology'])} edge(s) where the provider postdates the user")
    for row in sorted(report["chronology"], key=lambda r: -r.get("gap_years", 0)):
        if "gap_years" in row:
            print(
                f"  {row['user']} <- {row['provider']}  "
                f"user {row['user_onset']}, provider {row['provider_onset']} "
                f"(+{row['gap_years']}y)"
            )
        else:
            print(f"  {row['user']} <- {row['provider']}: {row['issue']}")
    print(f"\nACYCLICITY: {len(report['cycles'])} cycle(s)")
    for cycle in report["cycles"][:5]:
        print("  " + " -> ".join(cycle))


if __name__ == "__main__":
    main()
